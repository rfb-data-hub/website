#!/usr/bin/env python3
"""Regenerate the hero avatar orbit in src/pages/index.html.

The orbit is six concentric elliptical rings centred on the hero card's cell
stack (the .hero-floats box == the card box, so 100% == card width/height).
Depth reads from the OUTSIDE IN: the outer rings are the biggest and faintest
avatars (they are "far away"), each inner ring gets smaller and more opaque,
and the innermost ring matches the size of the avatars drawn inside the stack
(they render at 20-27 px, so 24 px) — the swarm visually feeds the cell.

    bearing b (deg) -> left = 50 + Rx*sin(b)
                      top  = 50 - Ry*cos(b),  Ry = 0.68 * Rx

Bearings are evenly spaced per ring (plus a small seeded jitter) so no two
avatars ever pile up, and the opacity ramp is exponential (see OP_MIN/OP_MAX):
0.10 outside → 1.00 inside, slow first, steep near the cell. The outer rings
are full circles, so the faint ones cross into the text column, which sits
above this layer (.hero-copy z-index, see 05-hero.css).

The swarm stands still: every avatar is placed once and carries a fixed tilt
from TILTS, so it reads as loose rather than as a stamped grid. Nothing here
animates — an infinite animation on 72 images keeps the page producing frames
while the reader does nothing.

Rewrites everything between the ORBIT:BEGIN / ORBIT:END markers.
Usage: python3 scripts/gen-orbit.py [--check]
"""
import math
import re
import sys
import pathlib

# ---------- constants ----------
ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "src" / "pages" / "index.html"

RY = 0.68            # vertical squash of the rings
JITTER_DEG = 5.0     # bearing jitter, keeps the rings organic but apart
JITTER_SIZE = 0.05   # +/-5 % size jitter (never crosses a neighbouring ring)
SEED = 20261009

# (Rx in % of the card box, avatar count, size px) — inner -> outer.
# Size runs from the cell-stack size up to the biggest disc the orbit has
# (70 base, 73 with jitter). The stack's 17 avatars are 27–36 SVG units and
# render at ≈ 20–27 px (scale = card svg width / 620 ≈ 0.74), so the innermost
# ring is 24 px: the swarm keeps shrinking into the cell, never growing.
RINGS = [
    (30, 10, 24),
    (46, 12, 33),
    (62, 14, 42),
    (78, 14, 51),
    (94, 12, 60),
    (110, 10, 70),
]

# Opacity ramp, outside -> inside: exponential, so the swarm stays ghostly
# for the first rings and only firms up as it reaches the cell.
#   op(t) = OP_MIN * (OP_MAX/OP_MIN)**t ,  t = 0 outer … 1 inner
# 6 rings -> 0.10 · 0.16 · 0.25 · 0.40 · 0.63 · 1.00 (steps of ×1.58).
# Set OP_EXP = 1 for the plain geometric ramp; > 1 makes the start even slower.
OP_MIN = 0.10
OP_MAX = 1.00
OP_EXP = 1.0

# Static tilt in degrees, rotated over the avatars so neighbours differ;
# the orbit applies it in the markup and animates nothing.
TILTS = (-3.0, 2.0, 0.0)
BEGIN = "          <!-- ORBIT:BEGIN generated by scripts/gen-orbit.py — do not hand-edit -->"
END = "          <!-- ORBIT:END -->"


def opacity_for(ring, rings):
    """0.10 on the outer ring → 1.00 on the inner one, exponentially."""
    t = ring / (len(rings) - 1)          # 0 = outermost, 1 = innermost
    t **= OP_EXP                         # OP_EXP > 1 keeps the outer rings faint longer
    return OP_MIN * (OP_MAX / OP_MIN) ** t


# ---------- seeded RNG ----------
class Rand:
    """Deterministic LCG so the orbit is stable across runs."""

    def __init__(self, seed):
        self.state = seed & 0x7FFFFFFF

    def unit(self):
        self.state = (1103515245 * self.state + 12345) & 0x7FFFFFFF
        return self.state / 0x7FFFFFFF

    def span(self, lo, hi):
        return lo + (hi - lo) * self.unit()


# ---------- ellipse placement ----------
def build():
    rnd = Rand(SEED)
    lines, k = [], 0
    last = len(RINGS) - 1
    for ring, (rx, count, size) in enumerate(RINGS):
        opacity = opacity_for(last - ring, RINGS)   # ring 0 = innermost
        phase = ring * 23.0
        for j in range(count):
            bearing = math.radians(
                phase + 360.0 * j / count + rnd.span(-JITTER_DEG, JITTER_DEG))
            left = 50 + rx * math.sin(bearing)
            top = 50 - rx * RY * math.cos(bearing)
            width = round(size * (1 + rnd.span(-JITTER_SIZE, JITTER_SIZE)))
            tilt = TILTS[k % 3]
            # Two draws discarded on purpose: the LCG advances once per call, not
            # per value used — drop either and every later left/top/width moves.
            rnd.span(16, 30)
            rnd.span(0, 16)
            lines.append(
                '            <img src="assets/img/avatars/avatar-%02d.svg" alt="" '
                'style="left:%.1f%%;top:%.1f%%;width:%dpx;opacity:%.2f;'
                'transform:translate(-50%%,-50%%) rotate(%sdeg)">'
                % ((k % 20) + 1, left, top, width, opacity, format(tilt, "g")))
            k += 1
    return lines, k


def main():
    lines, count = build()
    # ---------- marker splice ----------
    block = "\n".join([BEGIN] + lines + [END])
    html = TARGET.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(html):
        sys.exit("markers %s / %s not found in %s" % (BEGIN, END, TARGET))
    new = pattern.sub(lambda _m: block, html)
    # ---------- --check mode ----------
    # scripts/check.sh runs this file with --check and fails the build
    # when the block between the markers is not what build() produces.
    if "--check" in sys.argv:
        print("no change" if new == html else "STALE: run scripts/gen-orbit.py")
        return 0 if new == html else 1
    TARGET.write_text(new, encoding="utf-8")
    print("%d avatars in %d rings" % (count, len(RINGS)))
    for ring, (rx, n, size) in enumerate(RINGS):
        print("  Rx %3d%%  n=%2d  %dpx  opacity %.2f"
              % (rx, n, size, opacity_for(len(RINGS) - 1 - ring, RINGS)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
